/**
 * 약관과 방침이 공통으로 쓰는 운영 주체 정보.
 *
 * **한 곳에만 둔다.** 두 문서에 각각 적으면 한쪽만 고쳐져 갈라지고, 법적 문서가
 * 갈라지면 어느 쪽이 유효한지 다투게 된다 (11-docs-architecture.md §2.1).
 *
 * `{{...}}` 가 남아 있으면 **아직 채워지지 않은 값**이다. 그 상태로 배포되면
 * 이용자가 빈칸을 보게 되므로, `frontend/src/__tests__/legal.test.tsx` 가 막는다.
 *
 * 근거: plan/DONE.md M1-T2
 */
export const OPERATOR = {
  /** 개인 운영이므로 상호·사업자번호는 두지 않는다 (사용자 선택). */
  형태: '개인' as const,
  /**
   * **법적 문서에는 이름을 하나만 쓴다.**
   *
   * 핸들(`qazcde`)과 실명을 문서마다 다르게 쓰면 같은 사람인데 둘로 읽히고,
   * 약관의 계약 상대방이 흐려진다. 그리고 개인정보 보호법 제30조·시행령이
   * 개인정보 보호책임자의 **`성명`** 을 요구하므로 그 칸은 핸들로 갈음할 수 없다.
   * 핸들은 법적 신원이 아니라 저장소 계정 이름이므로 법적 문서에서 뺐다.
   *
   * 전자상거래법의 사업자 신원 표시 의무는 **영리 목적 판매**에 걸리므로 이 서비스에는
   * 적용되지 않는다 — 회원이 Google 에 직접 지불하고 운영자는 대가를 받지 않는다.
   * 다만 개인정보 보호법은 **영리 여부를 묻지 않는다.**
   */
  이름: '김진웅',
  연락처: 'qazcde.k@gmail.com',
  시행일: '2026-10-22',
} as const

/**
 * 법적 문서를 **사용자에게 보여도 되는가.**
 *
 * 처음에는 "빈칸이 있으면 검사가 실패한다" 로 걸었는데 그건 틀린 설계였다 —
 * CI 가 빨개져 **다른 작업 전부가 막힌다.** 막아야 할 것은 빌드가 아니라
 * **빈칸을 사용자에게 보여주는 것**이다. 그래서 링크 노출을 막는다.
 */
export function legalReady(): boolean {
  return unfilled().length === 0
}

/** 아직 안 채워진 칸. */
export function unfilled(): string[] {
  return Object.entries(OPERATOR)
    .filter(([, value]) => typeof value === 'string' && value.includes('{{'))
    .map(([name]) => name)
}
